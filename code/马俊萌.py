import turtle
t=turtle.Turtle()
t.speed(0)
def seagull(x, y, size):
     t.penup()
     t.goto(x, y)
     t.pendown()
     t.color("black")
     t.pensize(2)
     t.setheading(0)
     t.forward(size)        # 中间横线
     t.left(130)
     t.forward(size/2)      # 左边三角
     t.backward(size/2)
     t.setheading(0)
     t.right(130)
     t.forward(size/2)
t.penup()
t.goto(-400, 220)
t.pendown()
t.color("#ffddb3")
t.begin_fill()
for _ in range(2):
    t.forward(800)
    t.right(90)
    t.forward(273)
    t.right(90)
t.end_fill()
t.penup()
t.goto(-400,-53)
t.pendown()
t.color("#4096ee")
t.begin_fill()
for i in range(2):
   t.forward(800)
   t.right(90)
   t.forward(180)
   t.right(90)
t.end_fill()
t.penup()
t.goto(-380,-53)
t.pendown()
t.color("#4096ee")
t.pensize(2)
t.left(90)
for i in range(13):
   t.circle(-15,180)
   t.circle(15,180)
t.penup()
t.goto(-350,-53)
t.pendown()
t.color("#4096ee")
