import turtle
t=turtle.Turtle()
t.speed(0)
t.getscreen().bgcolor('black')
t.penup();t.goto(0,-180);t.pendown()
t.color('red','red')
t.begin_fill()
t.left(50)
t.circle(-180,60)
t.circle(150,120)
t.circle(-180,60)
t.end_fill()
t.color('green')
t.pensize(3)
t.left(180);t.fd(180)
t.left(90);t.fd(20)
t.left(180);t.fd(40)
t.color('green')
for _ in range(2):
    t.begin_fill()
    t.circle(60,90)
    t.left(90)
    t.circle(60,90)
    t.end_fill()
    t.left(180)
t.hideturtle()
turtle.done