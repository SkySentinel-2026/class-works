import turtle
import random

t=turtle.Turtle()
t.penup()
t.goto(200,150)
t.pendown()
t.pencolor("orange")
t.fillcolor("yellow")
t.begin_fill()
t.circle(40)
t.end_fill()
t.penup()
t.goto(-200,100)
t.pendown()
t.pencolor("orange")
t.fillcolor("orange")
t.begin_fill()
t.circle(20)
t.forward(40)
t.circle(25)
t.forward(30)
t.circle(20)
t.end_fill()
t.penup()
t.goto(-450,0)
t.pendown()
t.fillcolor("deepskyblue")
t.begin_fill()
for i in range(2):
    t.forward(900)
    t.right(90)
    t.forward(400)
    t.right(90)
t.end_fill()
t.penup()
t.pencolor("white")
for i in range(20):
    x_pos = random.randint(-400,400)
    y_pos = random.randint(-50,0)
    t.penup()
    t.goto(x_pos,y_pos)
    t.pensize(random.randint(1,3))
    t.pendown()
    t.forward(random.randint(10,40))
t.penup()
t.goto(0,0)
t.pendown()
t.pencolor("black")
t.forward(80)
t.left(90)
t.forward(80)
for i in range(4):
    t.forward(40)
    t.right(90)
t.right(180)
t.forward(80)
t.left(90)
t.forward(80)
t.right(143)
t.forward(50)
t.right(37)
t.forward(80)
t.right(37)
t.forward(50)
ts = turtle.getcanvas()
ts.postscript(file="artwork.png")
t.hideturtle()

turtle.done