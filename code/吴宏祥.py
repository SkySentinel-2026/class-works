import turtle

t=turtle.Turtle()
t.pensize(4)
t.color("blue")
t.fillcolor("yellow")
t.begin_fill()
t.shape("turtle")
for i in range(4):
   t.forward(200)
   t.right(90)
t.penup()
t.goto(-50,0)
t.pendown()
for i in range(3):
  t.forward(300)
  t.left(120)
t.end_fill()
t.penup()
t.goto(40,-20)
t.pendown()
t.fillcolor("blue")
t.begin_fill()
for i in range(4):
  t.forward(30)
  t.right(90)
t.penup()
t.goto(130,-20)
t.pendown()
for i in range(4):
  t.forward(30)
  t.right(90)
t.end_fill()
t.penup()
t.goto(70,-140)
t.pendown()
t.fillcolor("brown")
t.begin_fill()
for i in range(4):
  t.forward(60)
  t.right(90)
t.penup()
t.goto(110,-170)
t.pendown()
t.circle(2)
t.end_fill()
