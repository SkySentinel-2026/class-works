import turtle
turtle.bgcolor("lightblue")
t = turtle.Turtle()
t.speed(8)
t.fillcolor("lightgreen")
t.penup()
t.goto(0,-1000)
t.pendown()
t.begin_fill()
t.circle(500)
t.end_fill()
t.penup()
t.goto(-175,-50)
t.pendown()
t.fillcolor("lightyellow")
t.begin_fill()
for i in range(2):
    t.forward(120)
    t.left(90)
    t.forward(200)
    t.left(90)
t.end_fill()
t.penup()
t.goto(-115,-50)
t.pendown()
t.fillcolor("red")
