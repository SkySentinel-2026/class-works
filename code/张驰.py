import turtle
t=turtle.Turtle()
t.speed(0)
t.color("red")
t.pensize(3)
for i in range(4):
    t.forward(100)
    t.right(90)
t.penup()
t.goto(-10,0)
t.pendown()
for i in range(3):
    t.forward(120)
    t.left(120)
t.penup()
t.goto(300,250)
t.pendown()
t.color("yellow")
t.begin_fill()
t.circle(40)
t.end_fill()
t.penup()
t.goto(25,120)
t.pendown()
t.color("pink")
for i in range(36):
    t.forward(50)
    t.right(90)
    t.right(10)
turtle.done()
